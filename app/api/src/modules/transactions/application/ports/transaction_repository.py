from __future__ import annotations

from datetime import datetime
from typing import Protocol

from modules.transactions.domain.entities.transaction import Transaction
from modules.transfers.domain.entities.transfer import Transfer


class TransactionRepositoryPort(Protocol):
    async def save(self, tx: Transaction) -> None: ...
    async def find_by_id(self, tx_id: str) -> Transaction | None: ...
    async def list_by_user(self, user_id: str, *, from_date: datetime | None = None, to_date: datetime | None = None, account_id: str | None = None, type: str | None = None) -> list[Transaction]: ...
    async def delete(self, tx_id: str) -> None: ...


class TransferRepositoryPort(Protocol):
    async def save(self, transfer: Transfer) -> None: ...
    async def find_by_id(self, transfer_id: str) -> Transfer | None: ...
    async def delete(self, transfer_id: str) -> None: ...
